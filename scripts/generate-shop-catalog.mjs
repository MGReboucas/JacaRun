// Shared catalog source; the server remains authoritative for prices and delivery.
import { readFileSync, writeFileSync } from 'node:fs';
const root=new URL('../',import.meta.url);
const items=JSON.parse(readFileSync(new URL('server/catalog.json',root),'utf8'));
if(items.length!==27 || new Set(items.map(i=>i.sku)).size!==items.length) throw Error('Expected 27 unique products');
const format=n=>n.toLocaleString('pt-BR');
const rows=items.map(item=>{
  if(![item.cents,item.rays,item.coins].every(Number.isSafeInteger) || item.cents<=0 || item.rays<0 || item.coins<0) throw Error('Invalid product');
  const title=[item.rays && format(item.rays)+' raios',item.coins && format(item.coins)+' moedas'].filter(Boolean).join(' + ');
  const price='R$ '+(item.cents/100).toFixed(2).replace('.',',');
  return `    {${JSON.stringify(item.sku)}, ${JSON.stringify(title)}, ${JSON.stringify(price)}, ${item.cents}, ${item.rays}, ${item.coins}}`;
});
const result=`// Generated by scripts/generate-shop-catalog.mjs from server/catalog.json. Do not edit.\n#pragma once\n#include <array>\nstruct OnlineShopItem { const char* sku; const char* title; const char* price; int cents; int rays; int coins; };\ninline constexpr int OnlineShopItemsPerTab = 9;\ninline constexpr int OnlineShopPageSize = 3;\ninline constexpr int OnlineShopPageCount = 3;\ninline constexpr std::array<OnlineShopItem, 27> OnlineShopCatalog{{\n${rows.join(',\n')}\n}};\n`;
const path=new URL('visual/Source/OnlineShopCatalog.h',root);
if(process.argv.includes('--check')) { if(readFileSync(path,'utf8')!==result) throw Error('Run node scripts/generate-shop-catalog.mjs'); }
else writeFileSync(path,result);
