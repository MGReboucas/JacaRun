# Read alpha bounds only; does not modify source images.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition @'
using System;
using System.Drawing;
public static class JacaAtlasBounds {
    public static string Read(string path, string name) {
        using(var image=new Bitmap(path)) {
            if(image.Width!=1536 || image.Height!=1024 || image.GetPixel(0,0).A>16)
                throw new Exception("Atlas dimensions/transparency invalid: "+path);
            string output="inline constexpr AtlasCrop "+name+"[] = {\n";
            for(int frame=0;frame<8;frame++) {
                int left=(frame%4)*384, top=(frame/4)*512;
                // Horizontal action silhouettes extend slightly into their left gutter.
                if(name=="ActionCrops" && frame%4==3) left-=32;
                int right=(frame%4+1)*384, bottom=top+512;
                if(name=="ActionCrops" && frame%4==2) right-=32;
                int x0=right,y0=bottom,x1=left,y1=top;
                for(int y=top;y<bottom;y++) for(int x=left;x<right;x++)
                    if(image.GetPixel(x,y).A>180) {
                        x0=Math.Min(x0,x);y0=Math.Min(y0,y);x1=Math.Max(x1,x);y1=Math.Max(y1,y);
                    }
                if(x1<=x0 || y1<=y0) throw new Exception("Empty frame");
                x0=Math.Max(left,x0-2); y0=Math.Max(top,y0-2);
                x1=Math.Min(right-1,x1+2); y1=Math.Min(bottom-1,y1+2);
                output+="    {"+x0+","+y0+","+(x1-x0+1)+","+(y1-y0+1)+"},\n";
            }
            return output+"};\n";
        }
    }
}
'@
$root=Split-Path $PSScriptRoot
$header="#pragma once`n// Generated by scripts/inspect-character-atlases.ps1; source PNGs remain unchanged.`nstruct AtlasCrop { int x, y, width, height; };`n"
foreach($pair in @(@('run','RunCrops'),@('idle','IdleCrops'),@('actions','ActionCrops'))) {
    $header += [JacaAtlasBounds]::Read((Join-Path $root "visual/Content/art/jaca-$($pair[0])-v2.png"),$pair[1])
}
[IO.File]::WriteAllText((Join-Path $root 'visual/Source/CharacterAtlas.h'),$header,[Text.UTF8Encoding]::new($false))
Write-Output $header
