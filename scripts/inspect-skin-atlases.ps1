# Read complete character artwork; never composite or modify the PNGs.
param([switch]$AllowIncomplete)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition @'
using System;
using System.Drawing;
using System.Globalization;
public static class DressedJacaBounds {
    public static string Read(string path, double density, int rows, string filename) {
        using(var image=new Bitmap(path)) {
            if(image.GetPixel(0,0).A>16 || image.Width<200 || image.Height<200)
                throw new Exception("Expected transparent 4x6 character atlas: "+path);
            if(density<=0 || density>4 || double.IsNaN(density)) throw new Exception("Invalid density");
            string result="    {\"art/skins/"+filename+"\", "+
                density.ToString("0.000000",CultureInfo.InvariantCulture)+"f, {{\n";
            // Locate complete connected silhouettes instead of cutting at grid lines.
            // Long tails in slide/fall poses legitimately extend into a cell gutter.
            for(int row=0;row<rows;row++) {
                int top=row*image.Height/rows, bottom=(row+1)*image.Height/rows;
                int width=image.Width, height=bottom-top;
                bool[] pixels=new bool[width*height];
                int[] queue=new int[pixels.Length];
                Rectangle[] boxes=new Rectangle[4];
                int[] areas=new int[4];
                for(int y=0;y<height;y++) for(int x=0;x<width;x++)
                    pixels[y*width+x]=image.GetPixel(x,top+y).A>180;
                for(int seed=0;seed<pixels.Length;seed++) {
                    if(!pixels[seed]) continue;
                    int head=0,tail=1,x0=width,y0=height,x1=0,y1=0;
                    queue[0]=seed; pixels[seed]=false;
                    while(head<tail) {
                        int value=queue[head++], x=value%width, y=value/width;
                        x0=Math.Min(x0,x);y0=Math.Min(y0,y);x1=Math.Max(x1,x);y1=Math.Max(y1,y);
                        for(int dy=-1;dy<=1;dy++) for(int dx=-1;dx<=1;dx++) {
                            int nx=x+dx, ny=y+dy;
                            if(nx<0 || nx>=width || ny<0 || ny>=height) continue;
                            int next=ny*width+nx;
                            if(pixels[next]) { pixels[next]=false; queue[tail++]=next; }
                        }
                    }
                    int col=Math.Min(3,((x0+x1)/2)*4/width);
                    if(tail>areas[col]) { areas[col]=tail; boxes[col]=Rectangle.FromLTRB(x0,y0+top,x1+1,y1+top+1); }
                }
                for(int col=0;col<4;col++) {
                    if(areas[col]<400) throw new Exception("Missing connected pose "+(row*4+col)+": "+path);
                    var box=boxes[col];
                    int x0=Math.Max(0,box.Left-2), y0=Math.Max(top,box.Top-2);
                    int x1=Math.Min(width,box.Right+2), y1=Math.Min(bottom,box.Bottom+2);
                    result+="        {"+x0+","+y0+","+(x1-x0)+","+(y1-y0)+"},\n";
                }
            }
            return result+"    }}},\n";
        }
    }
}
'@
$root=Split-Path $PSScriptRoot
$layout=Get-Content -Raw (Join-Path $root 'visual/Content/art/skins/layout.json') | ConvertFrom-Json
$header=@'
#pragma once
// Generated by scripts/inspect-skin-atlases.ps1 from complete dressed sprites.
#include "CharacterAtlas.h"
#include <array>
struct DressedJacaAtlas {
    const char* file;
    float density;
    std::array<AtlasCrop,24> frames; // Idle 0..7, run 8..15, actions 16..23.
};
inline constexpr DressedJacaAtlas DressedJacaAtlases[] = {
'@
$header+="`n"
for($id=1;$id -le 15;$id++) {
    $path=Join-Path $root ('visual/Content/art/skins/jaca-{0:00}.png' -f $id)
    if(!(Test-Path -LiteralPath $path)) {
        if($AllowIncomplete) { Write-Output "Awaiting skin $id"; continue }
        throw "Missing skin $id : $path"
    }
    $header += [DressedJacaBounds]::Read($path,$layout.density[$id-1],6,('jaca-{0:00}.png' -f $id))
    Write-Output "Validated skin $id : 24 full character poses"
}
$header+="};`n"
if(!$AllowIncomplete) {
    $run = [DressedJacaBounds]::Read((Join-Path $root 'visual/Content/art/skins/jaca-05-run.png'),$layout.crownRunDensity,2,'jaca-05-run.png')
    $header += "inline constexpr DressedJacaAtlas CrownRunAtlas = " + $run.Trim().TrimEnd(',') + ";`n"
    foreach($state in @('idle','run')) {
        $entry=[DressedJacaBounds]::Read((Join-Path $root "visual/Content/art/skins/jaca-09-$state.png"),1.0,2,"jaca-09-$state.png")
        $name=if($state -eq 'idle') {'ExplorerIdleAtlas'} else {'ExplorerRunAtlas'}
        $header += "inline constexpr DressedJacaAtlas $name = " + $entry.Trim().TrimEnd(',') + ";`n"
    }
}
if(!$AllowIncomplete) {
    [IO.File]::WriteAllText((Join-Path $root 'visual/Source/DressedJacaAtlas.h'),$header,[Text.UTF8Encoding]::new($false))
}
